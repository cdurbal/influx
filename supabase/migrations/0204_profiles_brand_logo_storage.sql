-- 3. profiles.brand_logo_objects (04 §5.11 rule 3; stockage.md §5) -----------------------------------

do $$
begin
  if not exists (select 1 from pg_catalog.pg_type t
                  where t.typname = 'brand_logo_state'
                    and t.typnamespace = 'profiles'::regnamespace) then
    create type profiles.brand_logo_state as enum ('pending', 'active', 'purging');
  end if;
end
$$;

comment on type profiles.brand_logo_state is
  'Life of a brand logo object (stockage.md §3, §5): pending (row written, object not yet stored), '
  'active (the logo of the brand, one per account), purging (to remove from Storage by the task '
  'storage_purge); purged = row deleted.';

create table if not exists profiles.brand_logo_objects (
  id                     uuid        not null primary key default gen_random_uuid(),
  account_id             uuid        not null references profiles.advertiser_profiles (account_id),
  -- T9.3, T9.9: computed by the base, never a name or a path of the client
  object_key             text        not null
                                     generated always as
                                       (account_id::text || '/' || id::text || '.webp') stored,
  state                  profiles.brand_logo_state not null default 'pending',
  received_bytes         integer     not null,
  byte_size              integer,
  width                  smallint,
  height                 smallint,
  created_at             timestamptz not null default now(),
  activated_at           timestamptz,
  purge_requested_at     timestamptz,
  purge_attempts         smallint    not null default 0,
  last_purge_attempt_at  timestamptz,

  -- EC-L2B-08-2: one attempt through the relay (2 MiB), the WebP of the bucket (1 MiB, 512 px)
  constraint brand_logo_objects_received_bytes check (received_bytes between 1 and 2097152),
  constraint brand_logo_objects_byte_size check (byte_size between 1 and 1048576),
  constraint brand_logo_objects_sides check (width between 1 and 512 and height between 1 and 512),
  -- the stored output is described whole, or not at all
  constraint brand_logo_objects_stored_together
    check ((byte_size is null) = (width is null) and (width is null) = (height is null)),
  -- pending: nothing stored yet; active: stored and dated
  constraint brand_logo_objects_pending_unstored
    check (state <> 'pending' or (byte_size is null and activated_at is null)),
  constraint brand_logo_objects_active_complete
    check (state <> 'active' or (byte_size is not null and activated_at is not null)),
  -- purging, and only purging, carries the instant of the request
  constraint brand_logo_objects_purge_dated
    check ((state = 'purging') = (purge_requested_at is not null)),
  constraint brand_logo_objects_purge_attempts check (purge_attempts >= 0)
);

-- one logo per brand (stockage.md §5)
create unique index if not exists brand_logo_objects_one_active
  on profiles.brand_logo_objects (account_id) where state = 'active';
-- the task storage_purge (L2B-09): purging rows, and pending rows older than 15 minutes
create index if not exists brand_logo_objects_purge_idx
  on profiles.brand_logo_objects (state, created_at) where state <> 'active';

