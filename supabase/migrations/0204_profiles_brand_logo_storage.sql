-- Lot 2 / L2B, commit 08. The private bucket of the brand logo, one row per stored object, the
-- daily quotas, the policies of Supabase Storage (03 P10, §6.6; 04 §5.11; 18 T9.1, T9.3, T9.8,
-- T9.9). D80 and jalons/l2b/stockage.md §5 to §7 prevail over the prompt of 08: the bucket holds
-- the OUTPUT of the re-encoding only (WebP, 1 MiB), the row is written before the object, the key
-- is computed by the base, the quota is 10 uploads and 20 MiB received per account and UTC day.
--
-- 1. storage.buckets: `brand-logo`, private, allowed_mime_types {image/webp}, file_size_limit
--    1 048 576 (stockage.md §5; replaces "PNG, JPEG, WebP, 2 Mo" of the prompt). supabase/config.toml
--    unchanged. No other bucket (portfolio and verification-evidence: L2E, L2G).
-- 2. storage.objects and storage.buckets: a RESTRICTIVE policy `using (false) with check (false)`
--    for anon and authenticated (P10.6): no member, browser or key of theirs reaches an object or a
--    bucket, whatever permissive policy appears one day. apps/api reaches Storage with the secret
--    key only (service_role, BYPASSRLS), through src/platform/storage.ts (L2B-09). No influx_% role
--    holds any right on the schema storage (asserted below). On the hosted project the migration
--    role creates these policies through supautils.policy_grants (constat staging, 2026-11-02).
-- 3. profiles.brand_logo_objects: one row per object of the bucket (04 §5.11 rule 3), written
--    BEFORE the object (stockage.md §3 (b)); object_key GENERATED by the base,
--    `<account_id>/<id>.webp` (T9.3, T9.9: never a name of the client, never a traversal); state
--    pending (row written, object not yet), active (the logo, one per account), purging (to remove
--    from Storage); purged = row deleted (by the hourly task storage_purge of L2B-09). No member
--    writes a row: the transitions are the functions of section 5.
-- 4. profiles.storage_quotas (per bucket: uploads and bytes received per day) and
--    profiles.storage_daily_usage (account, bucket, UTC day, count, bytes): every attempt that
--    reaches (b) is counted, before any decoding; the refusal at the exact frontier is the base's.
-- 5. Five member doors, SECURITY DEFINER owned by influx_identity_definer (EC-L2B-06-1), EXECUTE
--    for influx_advertiser only, the account read from the transaction context (03 P2):
--      begin_brand_logo_upload(received bytes)  (b) quota consumed, row pending; returns id and key
--      discard_brand_logo_upload(id)            (c) refused by the checks: the pending row deleted
--      fail_brand_logo_upload(id)               (d) Storage write failed: pending -> purging
--      activate_brand_logo(id, bytes, sides)    (e) pending -> active, the previous active -> purging
--      remove_own_brand_logo()                  DELETE: active -> purging
-- 6. Rights of the data subject (04 §9.2; fiche invariant 5; stockage.md §7):
--    privacy.export_document() and privacy.execute_request() recreated FROM THEIR 0202 VERSION by
--    their owner influx_privacy_definer. Export: advertiser_profile carries `logo_files`, the
--    metadata of each object (state, size, sides, dates), never the bytes nor the key. Erasure:
--    every logo row of the account passes to purging (the logo unreachable at once, removed by the
--    task), its daily usage deleted.
--
-- EC-L2B-08 (micro-gaps, the safest choice):
--   EC-L2B-08-1  quota refusal: SQLSTATE 54000 program_limit_exceeded, message
--                upload_quota_exceeded, DETAIL `uploads` or `bytes`; apps/api answers 429 with
--                Retry-After until the next UTC midnight (stockage.md §6). A refused attempt counts
--                nothing (its transaction is rolled back).
--   EC-L2B-08-2  received bytes of one attempt: 1 to 2 097 152 (the relay limit, PP-9 amended by
--                D80); the stored WebP: 1 to 1 048 576, sides 1 to 512 (stockage.md §1: 512 x 512).
--   EC-L2B-08-3  the logo transitions are technical states of an object, not a status of the
