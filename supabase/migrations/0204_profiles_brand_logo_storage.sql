-- (c) Refused by the checks of the bytes: the pending row deleted --------------------------------
create or replace function profiles.discard_brand_logo_upload(p_logo_id uuid)
returns boolean
language plpgsql
volatile
security definer
set search_path = ''
as $$
declare
  v_account  uuid := influx.current_account_id();
begin
  if v_account is null or influx.current_account_role() is distinct from 'advertiser' then
    raise exception 'forbidden' using errcode = 'insufficient_privilege';
  end if;
  delete from profiles.brand_logo_objects l
   where l.id = p_logo_id and l.account_id = v_account and l.state = 'pending';
  return found;
end
$$;

