-- (b) The quota consumed and the row written, before any byte is decoded --------------------------
create or replace function profiles.begin_brand_logo_upload(p_received_bytes integer)
returns table (
  logo_id     uuid,
  object_key  text
)
language plpgsql
volatile
security definer
set search_path = ''
as $$
#variable_conflict use_column
declare
  -- the account comes from the transaction context (03 P2), never a parameter
  v_account  uuid := influx.current_account_id();
  v_day      date := (pg_catalog.now() at time zone 'UTC')::date;
  v_quota    record;
  v_usage    record;
  v_id       uuid;
  v_key      text;
begin
  if v_account is null or influx.current_account_role() is distinct from 'advertiser' then
    raise exception 'forbidden' using errcode = 'insufficient_privilege';
  end if;
  perform 1 from profiles.advertiser_profiles p
    join identity.accounts a on a.id = p.account_id and a.status = 'active'
   where p.account_id = v_account;
  if not found then
    raise exception 'forbidden' using errcode = 'insufficient_privilege';
  end if;
  -- EC-L2B-08-2: what the relay may carry
  if p_received_bytes is null or p_received_bytes < 1 or p_received_bytes > 2097152 then
    raise exception 'received bytes out of range' using errcode = 'invalid_parameter_value';
  end if;

  select q.max_uploads_per_day, q.max_bytes_per_day
    into v_quota
    from profiles.storage_quotas q
   where q.bucket_id = 'brand-logo';
  if not found then
    raise exception 'no quota for brand-logo' using errcode = 'object_not_in_prerequisite_state';
  end if;

  insert into profiles.storage_daily_usage (account_id, bucket_id, usage_day)
  values (v_account, 'brand-logo', v_day)
  on conflict (account_id, bucket_id, usage_day) do nothing;

  -- The row lock serialises two concurrent uploads of the account (T9.8 at the exact frontier).
  select u.upload_count, u.received_bytes
    into v_usage
    from profiles.storage_daily_usage u
   where u.account_id = v_account and u.bucket_id = 'brand-logo' and u.usage_day = v_day
     for update;

  if v_usage.upload_count + 1 > v_quota.max_uploads_per_day then
    raise exception 'upload_quota_exceeded'
      using errcode = 'program_limit_exceeded', detail = 'uploads';
  end if;
  if v_usage.received_bytes + p_received_bytes > v_quota.max_bytes_per_day then
    raise exception 'upload_quota_exceeded'
      using errcode = 'program_limit_exceeded', detail = 'bytes';
  end if;

  update profiles.storage_daily_usage u
     set upload_count = u.upload_count + 1,
         received_bytes = u.received_bytes + p_received_bytes
   where u.account_id = v_account and u.bucket_id = 'brand-logo' and u.usage_day = v_day;

  insert into profiles.brand_logo_objects as l (account_id, received_bytes)
  values (v_account, p_received_bytes)
  returning l.id, l.object_key into v_id, v_key;

  return query select v_id, v_key;
end
$$;

