--                the moderation of a changed logo (06 RG18) comes with L2C.
--   EC-L2B-08-4  agent and admin read brand_logo_objects in aal2, as the other tables of the
--                profile (0202); the owner reads his rows; nobody reads the quotas nor the usage
--                but the owner of the doors (and the erasure for the usage).
--   EC-L2B-08-5  quota table keyed by the bucket id, a closed list (`brand-logo`): the later
--                buckets amend it; no foreign key into storage (a schema of Supabase).
--
-- ROLLBACK (before any logo is stored): recreate privacy.export_document() and
-- privacy.execute_request() as in 0202 (as influx_privacy_definer); drop the five functions of
-- section 5; drop table profiles.storage_daily_usage, profiles.storage_quotas,
