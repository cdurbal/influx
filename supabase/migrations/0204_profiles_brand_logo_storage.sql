-- 8. End-state assertions ---------------------------------------------------------------------------

do $$
declare
  c_tables constant text[] := array[
    'profiles.brand_logo_objects', 'profiles.storage_quotas', 'profiles.storage_daily_usage'];
  v_def  record;
  v_bad  text;
begin
  -- 03 P10.1, 18 T9.1: every bucket private, brand-logo as stockage.md §5 sets it
  select string_agg(b.id, ', ') into v_bad from storage.buckets b where b.public is not false;
  if v_bad is not null then
    raise exception 'public bucket(s): %', v_bad;
  end if;
  if not exists (select 1 from storage.buckets b
                  where b.id = 'brand-logo' and b.public = false
                    and b.file_size_limit = 1048576
                    and b.allowed_mime_types = array['image/webp']) then
    raise exception 'the bucket brand-logo is not private, WebP only, 1 MiB';
  end if;

  -- 03 P10.6: the restrictive policy on storage.objects and storage.buckets
  select string_agg(t, ', ') into v_bad
    from unnest(array['objects', 'buckets']) t
   where not exists (select 1 from pg_catalog.pg_policies p
                      where p.schemaname = 'storage' and p.tablename = t
                        and p.policyname = 'influx_no_member_access'
                        and p.permissive = 'RESTRICTIVE' and p.cmd = 'ALL'
                        and p.roles = array['anon', 'authenticated']::name[]
                        and p.qual = 'false' and p.with_check = 'false');
  if v_bad is not null then
    raise exception 'restrictive policy missing on storage.%', v_bad;
  end if;

  -- stockage.md §5: no influx_% role holds any right on the schema storage
  select string_agg(r.rolname, ', ') into v_bad
    from pg_catalog.pg_roles r
   where r.rolname like 'influx\_%'
     and (pg_catalog.has_schema_privilege(r.oid, 'storage', 'USAGE, CREATE')
          or pg_catalog.has_table_privilege(r.oid, 'storage.objects',
                                            'SELECT, INSERT, UPDATE, DELETE, TRUNCATE')
          or pg_catalog.has_table_privilege(r.oid, 'storage.buckets',
                                            'SELECT, INSERT, UPDATE, DELETE, TRUNCATE'));
  if v_bad is not null then
    raise exception 'influx role(s) with a right on storage: %', v_bad;
  end if;

  -- no execution role writes a logo row, the quotas or the usage; influx_creator reads nothing
  select string_agg(r || ' ' || p || ' ' || t, ', ') into v_bad
    from unnest(c_tables) t,
         unnest(array['influx_advertiser', 'influx_creator', 'influx_agent', 'influx_admin',
                      'influx_auth', 'influx_worker', 'influx_ops', 'influx_privacy']) r,
         unnest(array['INSERT', 'UPDATE', 'DELETE']) p
   where pg_catalog.has_table_privilege(r, t, p)
      or (p <> 'DELETE' and pg_catalog.has_any_column_privilege(r, t, p));
  if v_bad is not null then
    raise exception 'execution role(s) writing a table of the logo: %', v_bad;
  end if;
  select string_agg(t, ', ') into v_bad
    from unnest(c_tables) t
   where pg_catalog.has_any_column_privilege('influx_creator', t, 'SELECT');
  if v_bad is not null then
    raise exception 'influx_creator reads: %', v_bad;
  end if;

  -- RLS enabled and forced
  select string_agg(c.oid::regclass::text, ', ') into v_bad
    from pg_catalog.pg_class c
   where c.oid = any (c_tables::regclass[])
     and not (c.relrowsecurity and c.relforcerowsecurity);
  if v_bad is not null then
    raise exception 'row level security not enabled and forced on: %', v_bad;
  end if;

  -- the five doors: SECURITY DEFINER, influx_identity_definer, empty search_path, influx_advertiser
  for v_def in
    select * from (values
      ('profiles.begin_brand_logo_upload(integer)'),
      ('profiles.discard_brand_logo_upload(uuid)'),
      ('profiles.fail_brand_logo_upload(uuid)'),
      ('profiles.activate_brand_logo(uuid, integer, integer, integer)'),
      ('profiles.remove_own_brand_logo()')
